module.exports = function chinese(r) {
  const pools = [];

  // 相反詞：雙向提問
  const antonymOf = new Map();
  for (const [a, b] of ANTONYMS) {
    antonymOf.set(a, b);
    antonymOf.set(b, a);
  }
  const antWords = [...antonymOf.keys()];
  const synGroupOf = new Map();
  SYNONYMS.forEach((g, i) => g.forEach((w) => synGroupOf.set(w, i)));
  const antItems = [];
  for (const [w, opp] of antonymOf) {
    const sameLen = antWords.filter((x) => x.length === w.length && x !== w && x !== opp && antonymOf.get(x) !== w);
    antItems.push(mc(r, { grade: w.length === 1 ? 1 : 3, topic: '相反詞', stem: `「${w}」的相反詞是哪一個？`,
      answer: opp, distractors: r.shuffle(sameLen), explanation: `「${w}」和「${opp}」意思相反` }));
  }
  pools.push({ topic: '相反詞', items: antItems });

  // 近義詞：同組內兩兩提問；干擾選項取自其他組
  const allSyn = SYNONYMS.flat();
  const synItems = [];
  SYNONYMS.forEach((group, gi) => {
    for (const w of group) {
      for (const s of group) {
        if (s === w) continue;
        const others = allSyn.filter((x) => synGroupOf.get(x) !== gi && antonymOf.get(x) !== w);
        synItems.push(mc(r, { grade: 3, topic: '近義詞', stem: `「${w}」的近義詞是哪一個？`, answer: s,
          distractors: r.shuffle(others), explanation: `「${w}」和「${s}」意思相近` }));
      }
    }
  });
  pools.push({ topic: '近義詞', items: synItems });

  // 辨別哪一組是相反詞／近義詞
  const pairItems = [];
  const fmt = ([a, b]) => `${a}－${b}`;
  const synPairs = SYNONYMS.map((g) => [g[0], g[1]]);
  for (const p of ANTONYMS.filter((x) => x[0].length === 2)) {
    pairItems.push(mc(r, { grade: 3, topic: '詞語關係', stem: '下列哪一組詞語是「相反詞」？', answer: fmt(p),
      distractors: r.sample(synPairs, 3).map(fmt), explanation: `「${p[0]}」和「${p[1]}」意思相反，其他選項是近義詞` }));
  }
  for (const p of synPairs) {
    const ants = ANTONYMS.filter((x) => x[0].length === 2);
    pairItems.push(mc(r, { grade: 3, topic: '詞語關係', stem: '下列哪一組詞語是「近義詞」？', answer: fmt(p),
      distractors: r.sample(ants, 3).map(fmt), explanation: `「${p[0]}」和「${p[1]}」意思相近，其他選項是相反詞` }));
  }
  pools.push({ topic: '詞語關係', items: pairItems });

  // 量詞
  pools.push({ topic: '量詞', items: MEASURE_WORDS.map(([noun, ...ok]) => mc(r, {
    grade: 2, topic: '量詞', stem: `一（　）${noun}，括號中應填哪一個量詞最恰當？`, answer: ok[0],
    distractors: r.shuffle(MEASURE_POOL.filter((m) => !ok.includes(m))), explanation: `我們說「一${ok[0]}${noun.replace(/（.*）/, '')}」` })) });

  // 部首：直接題與挑選題
  const radKeys = Object.keys(RADICALS);
  const radOf = new Map();
  for (const k of radKeys) for (const ch of RADICALS[k]) radOf.set(ch, k);
  const radDirect = [];
  const radPick = [];
  for (const [ch, rad] of radOf) {
    radDirect.push(mc(r, { grade: 2, topic: '部首', stem: `「${ch}」的部首是什麼？`, answer: rad,
      distractors: r.shuffle(radKeys.filter((k) => k !== rad)), explanation: `「${ch}」屬於「${rad}」部` }));
    const others = [...radOf.keys()].filter((c) => radOf.get(c) !== rad);
    radPick.push(mc(r, { grade: 2, topic: '部首', stem: `下列哪一個字的部首是「${rad}」？`,
      answer: ch, distractors: r.sample(others, 3), explanation: `「${ch}」屬於「${rad}」部` }));
  }
  pools.push({ topic: '部首', items: radDirect });
  pools.push({ topic: '部首', items: radPick });

  // 成語：填字（每個成語挖不同位置）與意思
  const idiomChars = [...new Set(IDIOMS.map(([w]) => w).join(''))];
  const fillItems = [];
  for (const [w, meaning] of IDIOMS) {
    const positions = r.sample([0, 1, 2, 3], 3);
    for (const pos of positions) {
      const blank = w.slice(0, pos) + '（　）' + w.slice(pos + 1);
      fillItems.push(mc(r, { grade: 4, topic: '成語', stem: `成語填空：${blank}`, answer: w[pos],
        distractors: r.shuffle(idiomChars.filter((c) => !w.includes(c))),
        explanation: `${w}：${meaning}` }));
    }
  }
  pools.push({ topic: '成語', items: fillItems });
  pools.push({ topic: '成語', items: IDIOMS.map(([w, meaning]) => mc(r, {
    grade: 4, topic: '成語', stem: `成語「${w}」的意思是？`, answer: meaning,
    distractors: r.sample(IDIOMS.filter((x) => x[0] !== w).map((x) => x[1]), 3), explanation: `${w}：${meaning}` })) });
  pools.push({ topic: '成語', items: IDIOMS.map(([w, meaning]) => mc(r, {
    grade: 4, topic: '成語', stem: `「${meaning}」可以用哪一個成語來形容？`, answer: w,
    distractors: r.sample(IDIOMS.filter((x) => x[0] !== w).map((x) => x[0]), 3), explanation: `${w}：${meaning}` })) });

  return pools;
};
