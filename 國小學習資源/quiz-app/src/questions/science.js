// 槓桿平衡：左邊砝碼數 × 距離 = 右邊砝碼數 × 距離
function leverItems(r) {
  const out = [];
  const seen = new Set();
  let guard = 0;
  while (out.length < 150 && guard++ < 3000) {
    const wl = r.int(1, 6);
    const dl = r.int(1, 6);
    const dr = r.int(1, 6);
    const prod = wl * dl;
    if (prod % dr !== 0 || dl === dr) continue;
    const wr = prod / dr;
    const stem = `槓桿左邊距離支點 ${dl} 格處掛 ${wl} 個砝碼，右邊距離支點 ${dr} 格處要掛幾個砝碼才能平衡？`;
    if (seen.has(stem)) continue;
    seen.add(stem);
    out.push(mc(r, { grade: 6, topic: '槓桿', stem, answer: wr,
      distractors: [wl, wr + 1, wr - 1, wr + 2, dl, wr * 2, wr + 3, wr + 4].filter((x) => x > 0 && x !== wr),
      explanation: `${wl} × ${dl} = ${prod}，${prod} ÷ ${dr} = ${wr}` }));
  }
  return out;
}

